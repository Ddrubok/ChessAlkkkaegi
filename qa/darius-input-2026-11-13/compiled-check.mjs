import assert from 'node:assert/strict';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { preview } from '../../web/node_modules/vite/dist/node/index.js';
import { chromium } from '../../.orca/ui-check/node_modules/playwright/index.mjs';

const out=resolve('qa/darius-input-2026-11-13/compiled-final');
await mkdir(out,{recursive:false});
const server=await preview({root:resolve('web'),mode:'itch',logLevel:'error',preview:{host:'127.0.0.1',port:0,open:false}});
const origin='http://127.0.0.1:'+server.httpServer.address().port;
const browser=await chromium.launch({channel:'msedge',headless:true});
const result={scope:'Compiled itch build, no runtime instrumentation or SDK mocks; fresh local Edge context',errors:[],deniedOrigins:[],checks:[]};
try {
  result.build=JSON.parse(await readFile('web/dist-itch/build-info.json','utf8'));
  const context=await browser.newContext({viewport:{width:1920,height:1080},locale:'en-US',serviceWorkers:'block'});
  await context.route('**/*',route=>{const url=new URL(route.request().url());if(url.origin===origin)return route.continue();if(!result.deniedOrigins.includes(url.origin))result.deniedOrigins.push(url.origin);return route.abort();});
  await context.routeWebSocket('**/*',socket=>socket.close());
  const page=await context.newPage();page.on('pageerror',e=>result.errors.push(e.message));
  await page.goto(origin);
  const cue=page.locator('.tutorial-gesture circle');await cue.waitFor({timeout:30000});
  const x=Number(await cue.getAttribute('cx')),y=Number(await cue.getAttribute('cy'));
  // The visible cue is generated by the real inverse curve. Follow its endpoint.
  const path=await page.locator('.tutorial-gesture path').getAttribute('d');
  const end=Number(path.match(/ V ([\d.]+)/)?.[1]);assert(Number.isFinite(end));
  await page.mouse.move(x,y);await page.mouse.down();await page.mouse.move(x,end,{steps:12});await page.mouse.up();
  await page.locator('#feedback-start-stage').waitFor({timeout:20000});
  result.checks.push('real compiled tutorial cue pull/release reaches first-flick completion');
  await page.locator('#feedback-start-stage').click();
  await page.locator('.mastery-hud-objective').filter({hasText:'Stage 1/10'}).waitFor();
  for(const [width,height] of [[1920,1080],[1366,768]]) {
    await page.setViewportSize({width,height});await page.waitForTimeout(250);
    await page.screenshot({path:resolve(out,`stage1-${width}x${height}.png`)});
  }
  assert.equal(await page.evaluate(()=>typeof globalThis.__playtestQA),'undefined');
  assert.deepEqual(result.errors,[]);
  result.checks.push('stage1 renders at baseline-matched sizes; no page errors or test instrumentation');
  result.pass=true;
} catch(error) {result.failure=error.stack;process.exitCode=1;}
finally {await writeFile(resolve(out,'result.json'),JSON.stringify(result,null,2));await browser.close();await new Promise(resolve=>server.httpServer.close(resolve));console.log(JSON.stringify(result));}
