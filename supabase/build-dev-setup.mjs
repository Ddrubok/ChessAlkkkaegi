// Bundle the existing migrations, without credentials or production user data.
import { readFile, readdir, writeFile } from 'node:fs/promises';
const root = new URL('./', import.meta.url);
const migrations = (await readdir(new URL('migrations/', root))).filter(n => n.endsWith('.sql')).sort();
const inputs = ['bootstrap/new_project_base.sql', ...migrations.map(n => `migrations/${n}`), 'verify_ranked_match_registration.sql'];
const parts = await Promise.all(inputs.map(async name => {
  const sql = (await readFile(new URL(name, root), 'utf8')).replace(/^\uFEFF/, '').replace(/^\s*(?:BEGIN|COMMIT);[ \t]*\r?$/gim, '').replace(/[ \t]+\r?$/gm, '');
  return `-- Source: ${name}\n${sql.trim()}\n`;
}));
const sql = `-- GENERATED by node supabase/build-dev-setup.mjs. Do not edit this bundle.\n-- Run the ENTIRE file as postgres in the EMPTY chessalkkagi-dev project only.\n-- Stops if app tables or users already exist. All changes are one transaction.\nBEGIN;\n\n${parts.join('\n')}\nNOTIFY pgrst, 'reload schema';\nCOMMIT;\nSELECT 'chessalkkagi_dev_ready' AS status;\n`;
await writeFile(new URL('setup_dev_project.sql', root), sql);
console.log(`Generated setup_dev_project.sql from the fresh base and ${migrations.length} migrations.`);
