export class I18nManager {
  public static currentLang: LanguageCode = "en";
  private static listeners: Set<(lang: LanguageCode) => void> = new Set();

  /**
   * 언어 관리자 초기화
   * - 저장된 설정 우선
   * - 없으면 사용자의 브라우저 언어(ko, ja, zh-CN, de, fr, es, ru, pt-BR) 감지
   * - 지원하지 않는 언어는 기본 영어(en)로 자동 폴백
   */
  public static init(): void {
    if (typeof localStorage === "undefined" || typeof document === "undefined") return;
    const saved = localStorage.getItem("app_language") as LanguageCode | null;
    if (saved && LOCALES[saved]) {
      this.currentLang = saved;
      document.documentElement.lang = this.currentLang;
      return;
    }

    const browserLangs =
      Array.isArray(navigator.languages) && navigator.languages.length > 0
        ? navigator.languages
        : [navigator.language || ""];

    let detected: LanguageCode = "en";

    for (const rawLang of browserLangs) {
      if (!rawLang) continue;
      const lower = rawLang.toLowerCase();
      const code = lower.split("-")[0];

      if (code === "ko") {
        detected = "ko";
        break;
      } else if (code === "ja") {
        detected = "ja";
        break;
      } else if (code === "zh" || lower.includes("zh")) {
        detected = "zh-CN";
        break;
      } else if (code === "de") {
        detected = "de";
        break;
      } else if (code === "fr") {
        detected = "fr";
        break;
      } else if (code === "es") {
        detected = "es";
        break;
      } else if (code === "ru") {
        detected = "ru";
        break;
      } else if (code === "pt" || lower.includes("pt")) {
        detected = "pt-BR";
        break;
      } else if (code === "en") {
        detected = "en";
        break;
      }
    }

    this.currentLang = detected;
    document.documentElement.lang = this.currentLang;
  }

  /**
   * 현재 선택된 언어 코드 반환
   */
  public static getLanguage(): LanguageCode {
    return this.currentLang;
  }

  /**
   * 언어 변경
   */
  public static setLanguage(lang: LanguageCode): void {
    if (!LOCALES[lang]) return;
    this.currentLang = lang;
    localStorage.setItem("app_language", lang);
    document.documentElement.lang = lang;

    this.listeners.forEach((listener) => {
      try {
        listener(lang);
      } catch (err) {
        console.error("i18n listener error:", err);
      }
    });
  }

  /**
   * 언어 변경 구독
   */
  public static subscribe(listener: (lang: LanguageCode) => void): () => void {
    this.listeners.add(listener);
    return () => this.listeners.delete(listener);
  }

  /**
   * 텍스트 키 조회 및 파라미터 치환
   * 예: I18nManager.t("lobby.win_draw_loss", { wins: 5, draws: 1, losses: 2 })
   */
  public static t(path: string, params: Record<string, string | number> = {}): string {
    const [ns, key] = path.split(".");
    const dict = LOCALES[this.currentLang] || LOCALES["en"];
    const fallbackDict = LOCALES["en"];

    let text = dict?.[ns]?.[key] ?? fallbackDict?.[ns]?.[key] ?? path;

    if (typeof text === "string" && params) {
      Object.keys(params).forEach((pKey) => {
        text = text.replace(new RegExp(`\\{${pKey}\\}`, "g"), String(params[pKey]));
      });
    }

    return text;
  }
}

// 자동 초기화 실행
I18nManager.init();
